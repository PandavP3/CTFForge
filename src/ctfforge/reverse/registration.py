"""Lazy registration for native reverse-engineering analyzers."""
from ctfforge.core.registry import ToolRegistry
from ctfforge.core.tool import InteractiveInput as I, ToolSpec


def register_reverse_tools(registry: ToolRegistry) -> None:
    file_input = I("file", "Binary file path", "path", must_exist=True)
    registry.register_category("reverse", (
        ToolSpec("info", "reverse", "Identify binary formats and summarize architecture metadata.",
                 "ctfforge.reverse.binary_info:analyze", usage="ctfforge reverse info --file FILE",
                 help="Uses signatures and structural checks; supported formats include ELF, PE, Mach-O, and common archives.",
                 interactive_inputs=(file_input,)),
        ToolSpec("strings", "reverse", "Extract bounded printable ASCII and UTF-16LE strings with offsets.",
                 "ctfforge.reverse.strings:analyze",
                 usage="ctfforge reverse strings --file FILE [--min-length 4] [--encoding ascii|utf16le|both] [--limit 10000] [--output FILE]",
                 help="Extracted text is untrusted and is never executed; output files are created exclusively and never overwritten.",
                 interactive_inputs=(file_input,
                                     I("min_length", "Minimum string length", "int", default=4, minimum=1, maximum=256),
                                     I("encoding", "String encoding mode", choices=("ascii", "utf16le", "both"), default="both"),
                                     I("limit", "Maximum strings to return", "int", default=10000, minimum=1, maximum=100000),
                                     I("output", "Optional text export path", "path", required=False))),
        ToolSpec("entropy", "reverse", "Calculate overall and block-based Shannon entropy.",
                 "ctfforge.reverse.entropy:analyze", usage="ctfforge reverse entropy --file FILE [--block-size 4096]",
                 help="High entropy may indicate compression or encryption but is not proof.",
                 interactive_inputs=(file_input,
                                     I("block_size", "Block size in bytes", "int", default=4096, minimum=256, maximum=1048576))),
        ToolSpec("elf", "reverse", "Inspect ELF headers, program headers, sections, and section names.",
                 "ctfforge.reverse.elf:analyze", usage="ctfforge reverse elf --file FILE",
                 help="Supports ELF32/ELF64 and little/big endian headers; binaries are never executed.",
                 interactive_inputs=(file_input,)),
        ToolSpec("pe", "reverse", "Inspect PE/COFF headers, optional header, directories, and sections.",
                 "ctfforge.reverse.pe:analyze", usage="ctfforge reverse pe --file FILE",
                 help="Supports PE32 and PE32+; binaries are never executed.",
                 interactive_inputs=(file_input,)),
        ToolSpec("symbols", "reverse", "Inspect ELF symbol tables and PE import/export directories.",
                 "ctfforge.reverse.symbols:analyze", usage="ctfforge reverse symbols --file FILE",
                 help="Reports only symbols present in bounded ELF/PE structures; no symbol information is invented.",
                 interactive_inputs=(file_input,)),
        ToolSpec("disasm", "reverse", "Statically disassemble a bounded binary range with optional Capstone.",
                 "ctfforge.reverse.disassembly:analyze", optional_dependencies=("capstone",),
                 usage="ctfforge reverse disasm --file FILE [--arch x86|arm|arm64|mips --bits BITS]",
                 help="Never executes the input. Raw binaries require explicit architecture, bitness, and mode/endianness where needed.",
                 interactive_inputs=(file_input,
                    I("arch", "Architecture (blank uses reliable ELF/PE metadata)", choices=("x86", "arm", "arm64", "mips"), required=False),
                    I("bits", "Bitness (blank uses reliable ELF/PE metadata)", "int", required=False, minimum=16, maximum=64),
                    I("endian", "Endianness when needed", choices=("little", "big"), required=False),
                    I("mode", "ARM or MIPS mode when needed", choices=("arm", "thumb", "mips32", "mips64"), required=False),
                    I("offset", "File offset", "int", default=0, minimum=0),
                    I("address", "Optional virtual address", "int", required=False, minimum=0),
                    I("max_bytes", "Maximum bytes to decode", "int", default=4096, minimum=1, maximum=1048576),
                    I("max_instructions", "Maximum instructions", "int", default=1000, minimum=1, maximum=10000),
                    I("output", "Optional JSON export path", "path", required=False))),
        ToolSpec("instructions", "reverse", "Summarize instruction counts and control-flow groups from a bounded decode.",
                 "ctfforge.reverse.instruction_analysis:analyze", optional_dependencies=("capstone",),
                 usage="ctfforge reverse instructions --file FILE --arch x86 --bits 64",
                 help="Counts only decoded instructions; static counts do not establish program behavior.",
                 interactive_inputs=(file_input,
                    I("arch", "Architecture (blank uses reliable ELF/PE metadata)", choices=("x86", "arm", "arm64", "mips"), required=False),
                    I("bits", "Bitness (blank uses reliable ELF/PE metadata)", "int", required=False, minimum=16, maximum=64),
                    I("endian", "Endianness when needed", choices=("little", "big"), required=False),
                    I("mode", "ARM or MIPS mode when needed", choices=("arm", "thumb", "mips32", "mips64"), required=False),
                    I("offset", "File offset", "int", default=0, minimum=0),
                    I("address", "Optional virtual address", "int", required=False, minimum=0),
                    I("max_bytes", "Maximum bytes to decode", "int", default=4096, minimum=1, maximum=1048576),
                    I("max_instructions", "Maximum instructions", "int", default=1000, minimum=1, maximum=10000),
                    I("details", "Include decoded instruction details", "bool", default=False),
                    I("output", "Optional JSON export path", "path", required=False))),
        ToolSpec("functions", "reverse", "List function metadata present in ELF symbols or PE exports.",
                 "ctfforge.reverse.function_analysis:analyze",
                 usage="ctfforge reverse functions --file FILE",
                 help="Uses existing bounded ELF/PE parsers and reports symbol-derived functions only.",
                 interactive_inputs=(file_input,)),
        ToolSpec("packer", "reverse", "Inspect static packer signatures, sections, entropy, and entry-point layout.",
                 "ctfforge.reverse.packer_detection:analyze",
                 usage="ctfforge reverse packer --file FILE",
                 help="Indicators are heuristic; high entropy alone is not proof of packing or malware.",
                 interactive_inputs=(file_input,)),
        ToolSpec("external-status", "reverse", "Check whether optional file, readelf, and objdump executables are available.",
                 "ctfforge.reverse.external_tools:availability",
                 usage="ctfforge reverse external-status",
                 help="Uses executable lookup only; does not run or install the utilities."),
        ToolSpec("external-file", "reverse", "Identify a file using the optional external file utility.",
                 "ctfforge.reverse.external_tools:file_identification",
                 usage="ctfforge reverse external-file --file FILE [--max-output BYTES]",
                 help="Read-only invocation with bounded output and timeout; requires `file` on PATH.",
                 interactive_inputs=(file_input,
                    I("max_output", "Maximum stdout/stderr bytes each", "int", default=1000000, minimum=1, maximum=2000000))),
        ToolSpec("external-elf", "reverse", "Inspect ELF metadata using optional readelf.",
                 "ctfforge.reverse.external_tools:elf_analysis",
                 usage="ctfforge reverse external-elf --file FILE [--mode header|program-headers|sections|symbols|dynamic|relocations]",
                 help="Uses a fixed allowlist of read-only modes; requires `readelf` on PATH.",
                 interactive_inputs=(file_input,
                    I("mode", "readelf analysis mode", choices=("header", "program-headers", "sections", "symbols", "dynamic", "relocations"), default="header"),
                    I("max_output", "Maximum stdout/stderr bytes each", "int", default=1000000, minimum=1, maximum=2000000))),
        ToolSpec("external-objdump", "reverse", "Inspect supported binary metadata using optional objdump.",
                 "ctfforge.reverse.external_tools:objdump_analysis",
                 usage="ctfforge reverse external-objdump --file FILE [--mode file-headers|section-headers|disassembly|symbol-table|private-headers]",
                 help="Uses fixed read-only modes; disassembly is output-limited and never executes the target.",
                 interactive_inputs=(file_input,
                    I("mode", "objdump analysis mode", choices=("file-headers", "section-headers", "disassembly", "symbol-table", "private-headers"), default="file-headers"),
                    I("max_output", "Maximum stdout/stderr bytes each", "int", default=1000000, minimum=1, maximum=2000000))),
    ))
